"""Technique 6: the one point two grounds are tied at, and the board that never says where.

`docs/stitch-plan.md` S3. The whole statement writes **no copper** — see `language.Bridge` for the
two judges a copper tie would each need an exemption from, and `docs/stitch-plan.md` §8 item 4 for
why it is refused rather than exempted. So every test here is about what pcbc *says*, and the one
thing it must not do is change what pcbc writes: `netcheck.py` has a zero diff in this slice and
`test_bridge_needs_no_gate_change` is the assertion that keeps it that way.

Every board is read **read-only**, including the DS2 Addon's, which lives outside this repo. Nothing
in `~/Documents/MaD` is written by this suite, and nothing here reads `examples/**/layout/` — a
placed board is generated by `conftest.placed_board` (pure Python, no KiCad) and a routed one is
marked `kicad` + `krt` and skipped when the artifact is absent.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from pcbc.build import _bridge_gate, build_job
from pcbc.circuit import _untied_grounds, check_design
from pcbc.compile import compile_design
from pcbc.copper_bar import copper_bar
from pcbc.language import load_board
from boardtext import feet_of_text
from pcbc.route_checks import build_ctx, check_bridge
from pcbc.route_verify import bridge_ties
from conftest import copy_board, ds2_dir, write_split
from conftest import copy_board_file

ROOT = Path(__file__).resolve().parent.parent
EXAMPLES = ROOT / "examples"
FIXTURE = ROOT / "tests" / "fixtures" / "bridge" / "bridge.py"
DS2 = ds2_dir()
HAS_DS2 = (DS2 / "ds2_addon.py").exists()
DS2_ROUTED = DS2 / "layout" / "ds2_addon" / "routed" / "layout.kicad_pcb"


def _board(name: str) -> Path:
    if name == "ds2":
        return DS2 / "ds2_addon.py"
    if name == "bridge":
        return FIXTURE
    return EXAMPLES / name / f"{name}.py"


def _placed(name: str) -> Path:
    from conftest import placed_board

    return placed_board(name, _board(name))


def _write(tmp_path: Path, name: str, body: str) -> Path:
    p = tmp_path / f"{name}.py"
    write_split(p, body)
    return p


HEAD = '''from pcbc import Board, Bridge, Capacitor, Ground, NetReq, Place, Power, Resistor, SchPlace
V33 = Power("3V3")
GND = Ground("GND")
VDDA = Power("VDDA")
VSS = Ground("VSS")
c = dict(package="0805", manufacturer="Yageo", mpn="CC0805KRX7R9BB104", lcsc="C49678")
r = dict(package="0805", manufacturer="UniOhm", mpn="0805W8F0000T5E", lcsc="C17888")
'''
TAIL = '''Board(width=40, height=25, layers=2, stackup="jlcpcb_2l_1oz")
NetReq("3V3", "VDDA", kind="power", volts=3.3); NetReq("GND", "VSS", kind="power")
'''


