# What the placement says: no axis separates them, and where a tie would go
# ---------------------------------------------------------------------------------------------

# The four-axis overlap of the DS2 Addon's two grounds, recorded 2026-09-21 from a **freshly placed**
# board (`conftest.placed_board`), as (axis, GND interval, VSS interval, overlap) in mm. The
# projection is of pad centres: a centre interval is contained in its box interval, so an overlap of
# centres implies an overlap of boxes and never the reverse — the conservative direction for a test
# whose claim is "no straight line separates these two domains". Measured on boxes for comparison:
# 26.180 / 16.394 / 22.679 / 18.653 mm, every one of them larger.
#
# These are `docs/stitch-plan.md` §2(n)'s own four numbers, reproduced exactly. What did **not**
# reproduce is the sentence beside them there — "GND's interval is strictly INSIDE VSS's on all four
# axes" is true of `x` and `v` and false of `y` and `u`, where GND runs past VSS's high end. The
# claim the design rests on is the weaker and true one: **all four overlap**, so there is no moat to
# cut (`docs/stitch-plan.md` §8 item 5).
DS2_AXES = (
    ("x", (13.270, 37.750), (1.520, 41.928), 24.480),
    # (2026-10-02: the 2026-10-01 re-record for decision 4's moves is undone; ds2 is placed as at the checkpoint.)
    ("y", (4.916, 24.130), (3.200, 20.360), 15.444),
    ("u", (21.058, 43.756), (13.470, 41.668), 20.610),
    ("v", (-2.291, 14.506), (-13.322, 20.195), 16.797),
)


@pytest.mark.skipif(not HAS_DS2, reason="needs the DS2 Addon board (read-only, outside this repo)")
def test_ds2_has_no_axis_that_separates_its_two_grounds():
    design = load_board(_board("ds2"))
    job = compile_design(design)
    ctx = build_ctx(design, job, feet_of_text(design, _placed("ds2").read_text()))
    moves = check_bridge(ctx)
    assert len(moves) == 1
    move = moves[0]
    assert move.startswith("GND/VSS: no axis separates the two grounds")
    for axis, gnd, vss, overlap in DS2_AXES:
        assert f"{axis} [{gnd[0]:.3f},{gnd[1]:.3f}] vs [{vss[0]:.3f},{vss[1]:.3f}] overlap {overlap:.3f} mm" in move, (axis, move)
    # Where a tie would go: the nearest pad of one to a pad of the other **on another footprint**.
    # The overall nearest GND/VSS pads are `U1.4` and `U1.5`, 0.3070 mm apart on a 0.65 mm TSSOP
    # pitch — a distance that names why the two grounds have to be tied somewhere, not a place to
    # tie them, because no part goes between two pins of one package.
    assert "J1.2 and C7.2 come closest, 2.6675 mm apart" in move
    assert "no Bridge() names a part that ties them" in move and "Resistor(" not in move and "Place(\"" not in move, move


