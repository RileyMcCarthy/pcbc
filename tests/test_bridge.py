def test_bridge_needs_no_gate_change():
    """`netcheck.copper_nets` matches `(pad "N" ... (net "NAME"))` **inside footprint blocks only**
    and never reads a `(segment)` or a `(via)`. That is the measurement the whole slice rests on: a
    tie made of a part changes no pad binding, so `compare()` passes it and `netcheck.py` has a zero
    diff. A copper tie would instead need an exemption in two judges at once — see `language.Bridge`.
    """
    from pcbc.netcheck import copper_nets

    text = (
        '(kicad_pcb\n\t(footprint "R_0805"\n\t\t(property "Reference" "R11")\n'
        '\t\t(pad "1" smd rect (at 0 0) (size 1 1) (layers "F.Cu") (net 1 "VSS"))\n'
        '\t\t(pad "2" smd rect (at 2 0) (size 1 1) (layers "F.Cu") (net 2 "GND"))\n\t)\n'
        '\t(segment (start 0 0) (end 2 0) (width 0.25) (layer "F.Cu") (net 1 "VSS"))\n'
        '\t(via (at 1 0) (size 0.8) (drill 0.4) (layers "F.Cu" "B.Cu") (net 2 "GND"))\n)'
    )
    got = copper_nets(text)
    assert got == {"VSS": {("R11", "1")}, "GND": {("R11", "2")}}


def test_copper_bar_has_an_empty_bridge_entry_when_nobody_asks():
    bar = copper_bar('(kicad_pcb\n\t(net 0 "")\n)')
    assert bar["totals"]["bridge"] == {}
