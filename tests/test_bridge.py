# What `Bridge()` refuses, and where each refusal lives
# ---------------------------------------------------------------------------------------------


@pytest.mark.parametrize(
    "call,says",
    [
        ('Bridge("GND", "GND", at="R11")', "same net"),
        ('Bridge("GND", "VSS", at="R11", kind="weld")', "not one of"),
        ('Bridge("GND", "VSS", at=("J1.2", "J2.2"))', "names one part"),
        ('Bridge("GND", "VSS", at=("J1.2",), kind="off_board", why="x")', "two pads that leave the board"),
        ('Bridge("GND", "VSS", at=("J1", "J2"), kind="off_board", why="x")', "two pads that leave the board"),
        ('Bridge("GND", "VSS", at=("J1.2", "J2.2"), kind="off_board")', "needs why="),
    ],
)
def test_load_refuses_a_bridge_that_is_wrong_about_itself(tmp_path: Path, call: str, says: str):
    """Everything that is a property of the **call** is refused at load, before any net exists.

    Not the net names: `Path()`, `Bus()` and `Guard()` all defer those to `compile_constraints`, and
    a board is free to write its `Bridge()` line above its `Ground()` lines. Refusing an undeclared
    net at load would turn that ordering into an error about the wrong thing.
    """
    from pcbc.language import check_board

    board = _write(tmp_path, "b", HEAD + 'Resistor("R11", "0R", p1=VSS, p2=GND, **r)\n' + TAIL + call + "\n")
    fails = check_board(board)
    assert any(says in f for f in fails), fails


@pytest.mark.parametrize(
    "call,says",
    [
        ('Bridge("GND", "NOPE", at="R11")', "no net 'NOPE'"),
        ('Bridge("GND", "3V3", at="R11")', "a bridge ties two grounds, and 3V3 is not declared with Ground()"),
    ],
)
def test_compile_refuses_a_bridge_that_is_wrong_about_the_netlist(tmp_path: Path, call: str, says: str):
    from pcbc.language import check_board

    board = _write(tmp_path, "b", HEAD + 'Resistor("R11", "0R", p1=VSS, p2=GND, **r)\n' + TAIL + call + "\n")
    assert any(says in f for f in check_board(board)), check_board(board)


def test_compile_refuses_the_same_pair_bridged_twice(tmp_path: Path):
    from pcbc.language import check_board

    body = HEAD + 'Resistor("R11", "0R", p1=VSS, p2=GND, **r)\nResistor("R12", "0R", p1=VSS, p2=GND, **r)\n' + TAIL
    board = _write(tmp_path, "b", body + 'Bridge("GND", "VSS", at="R11")\nBridge("GND", "VSS", at="R12")\n')
    assert any("already bridged on line" in f for f in check_board(board)), check_board(board)


def test_check_design_refuses_a_tie_that_is_not_a_two_pin_part(tmp_path: Path):
    """The load-bearing rule of the whole statement, and the DS2 Addon is why it exists.

    `U1` there binds both grounds on sixteen pins. A part current goes *through* is a tie; a part
    referenced to both is what makes the split matter, and reading the second as the first would
    have declared the DS2 Addon tied.
    """
    from pcbc.language import check_board

    body = HEAD + 'Capacitor("C1", "100nF", p1=VDDA, p2=VSS, **c)\nResistor("R1", "1k", p1=GND, p2=VSS, **r)\n' + TAIL
    board = _write(tmp_path, "b", body + 'Bridge("GND", "VSS", at="C9")\n')
    assert any("no part C9" in f for f in check_board(board))


def test_check_design_refuses_a_second_part_joining_the_same_two_grounds(tmp_path: Path):
    from pcbc.language import check_board

    body = HEAD + 'Resistor("R11", "0R", p1=VSS, p2=GND, **r)\nResistor("R12", "0R", p1=VSS, p2=GND, **r)\n' + TAIL
    board = _write(tmp_path, "b", body + 'Bridge("GND", "VSS", at="R11")\n')
    assert any("also join" in f and "not one point" in f for f in check_board(board)), check_board(board)


def test_check_design_refuses_a_tie_whose_pads_are_not_one_per_net(tmp_path: Path):
    from pcbc.language import check_board

    body = HEAD + 'Resistor("R11", "0R", p1=V33, p2=GND, **r)\nCapacitor("C1", "100nF", p1=VDDA, p2=VSS, **c)\n' + TAIL
    board = _write(tmp_path, "b", body + 'Bridge("GND", "VSS", at="R11")\n')
    assert any("not one pad on GND and one on VSS" in f for f in check_board(board)), check_board(board)


def test_a_capacitor_tie_is_a_note_and_not_a_refusal(tmp_path: Path):
    """An AC bridge is a real choice on an isolated domain and a mistake on a shared one, and pcbc
    cannot tell which this is. So it says the consequence and does not stop the board."""
    from pcbc.language import check_board

    body = HEAD + 'Capacitor("C9", "100nF", p1=VSS, p2=GND, **c)\n' + TAIL
    board = _write(tmp_path, "b", body + 'Bridge("GND", "VSS", at="C9", kind="cap")\n')
    notes: list[str] = []
    assert [f for f in check_board(board, pcb=False, notes=notes) if "Bridge" in f] == []
    assert any("AC bridge" in n and "no DC reference" in n for n in notes), notes


def test_off_board_refuses_a_pad_that_is_not_on_the_net_it_is_written_for(tmp_path: Path):
    from pcbc.language import check_board

    body = HEAD + 'Capacitor("C1", "100nF", p1=VDDA, p2=VSS, **c)\nCapacitor("C3", "100nF", p1=V33, p2=GND, **c)\n' + TAIL
    board = _write(tmp_path, "b", body + 'Bridge("GND", "VSS", at=("C1.2", "C3.2"), kind="off_board", why="chassis stud")\n')
    assert any("C1.2 is not a pad of GND" in f for f in check_board(board)), check_board(board)


